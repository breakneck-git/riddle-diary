-- эмодзи (UTF-8): 4-байтные символы; U+2190–21FF стрелки, U+2300–23FF (⌛ ⏰), U+25A0–25FF фигуры (▶ ◻),
-- U+2600–27BF символы и дингбаты, U+2B00–2BFF (⭐ ⬛); одиночные ‼ ⁉ ℹ 〰 〽 ㊗ ㊙, ZWJ, кейкап, селектор варианта.
-- Многоточие, тире и кавычки (U+2010–2027, «») — не эмодзи
local EMOJI = { "[\240-\247]", "\226[\134\135\140-\143\152-\158\172-\175]", "\226[\150\151]",
  "\226\128\188", "\226\129\137", "\226\132\185", "\226\128\141", "\226\131\163", "\227\128[\176\189]",
  "\227\138[\151\153]", "\239\184\143" }

local function has_emoji(s)
  for _, p in ipairs(EMOJI) do
    if s:find(p) then return true end
  end
  return false
end

-- буква перед позицией i (латиница, цифра или кириллица \208/\209): слово начинается не в i
local function letter_before(s, i)
  if i == 1 then return false end
  local b = s:byte(i - 1)
  if b < 128 then return s:sub(i - 1, i - 1):find("[%w]") ~= nil end
  return b >= 128 and b <= 191 and i > 2 and (s:byte(i - 2) == 208 or s:byte(i - 2) == 209)
end

-- есть ли в s слово, начинающееся с запрещённого. Сверка со списками обоих языков всегда: фраза «по-русски» с
-- «server» или «network» внутри — тот же технический сбой (пулы «Методов» от этого не теряют ни одной фразы)
function texts.forbidden(s)
  local low = str.lower(s)
  for _, list in ipairs({ texts.FORBIDDEN.ru, texts.FORBIDDEN.en }) do
    for _, w in ipairs(list) do
      local i = 1
      while true do
        local a = low:find(w, i, true)
        if not a then break end
        if not letter_before(low, a) then return true end
        i = a + 1
      end
    end
  end
  return false
end

-- годна ли фраза s по правилам rule ({ max_cps, sentences }; texts.SETS, texts.INVITATION): не пустая (lang не
-- влияет — запрещённые слова сверяются по обоим языкам),
-- не длиннее max_cps знаков, без эмодзи, без разметки (* # ` _ [ ]), без запрещённых слов, не больше sentences
-- предложений
function texts.fits(rule, s, lang)
  if type(s) ~= "string" then return false end
  s = str.trim(s)
  return s ~= ""
    and str.utf8_len(s) <= rule.max_cps
    and not has_emoji(s)
    and not s:find("[%*#`_%[%]]")
    and select(2, s:gsub("[%.!?]+%s", "")) + 1 <= rule.sentences
    and not texts.forbidden(s)
end

-- фразы набора name от модели -> годные (texts.fits), по порядку, без повторов
function texts.clean(name, list, lang)
  local set = set_by_name(name)
  local kept, seen = {}, {}
  if not set or type(list) ~= "table" then return kept end
  for _, v in ipairs(list) do
    local s = str.trim(v)
    if not seen[s] and texts.fits(set, s, lang) then
      seen[s] = true
      kept[#kept + 1] = s
    end
  end
  return kept
end

