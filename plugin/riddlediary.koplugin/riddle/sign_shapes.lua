-- Шаблоны знаков управления (спека 2026-11-28-control-signs, подход А): по каждому знаку — список рисунков, рисунок —
-- список штрихов в формате виджета { p = { x1, y1, x2, y2, … } }, экранные px. Точки — вершины ломаной: glyph
-- передискретизует её по длине. glyph.match сверяет рисунок только с шаблоном того же числа штрихов (как нарисовано или
-- после склейки разрывов) — поэтому у стрелки по шаблону на 1 и на 2 штриха.
-- Пока синтетика (план, Task 1); заменяются рисунками владельца из лога devmode (Task 3).
local function stroke(...) return { p = { ... } } end

-- дуга окружности (cx, cy, r) от a0 до a1 градусов шагом step -> вершины x1, y1, x2, y2, … в out
local function arc(out, cx, cy, r, a0, a1, step)
  for a = a0, a1, step do
    out[#out + 1] = cx + r * math.cos(math.rad(a))
    out[#out + 1] = cy + r * math.sin(math.rad(a))
  end
  return out
end

return {
  -- стрелка вверх: древко снизу вверх, голова — с возвратом к острию; или древко и голова отдельно
  up = {
    { stroke(380, 700, 380, 300, 300, 400, 380, 300, 460, 400) },
    { stroke(380, 700, 380, 300), stroke(300, 400, 380, 300, 460, 400) },
  },
  -- стрелка вниз: то же, отражённое по вертикали около y = 500
  down = {
    { stroke(380, 300, 380, 700, 300, 600, 380, 700, 460, 600) },
    { stroke(380, 300, 380, 700), stroke(300, 600, 380, 700, 460, 600) },
  },
  -- полумесяц рожками влево: внешняя дуга, затем внутренняя обратно — одним штрихом
  moon = {
    { { p = arc(arc({}, 380, 500, 200, -110, 110, 10), 300, 500, 150, 70, -70, -10) } },
  },
  -- квадрат одним штрихом
  square = {
    { stroke(200, 300, 550, 300, 550, 650, 200, 650, 200, 300) },
  },
  -- молния: сверху справа вниз влево, вправо, вниз влево
  bolt = {
    { stroke(460, 250, 320, 480, 440, 480, 300, 750) },
  },
}
